// claude.ts — the Claude Code wiring, from the same sources as opencode's (.ai/install/opencode/):
//   node .ai/scripts/ai.mjs claude install [--with-permissions]   once per machine, in ~/.claude ($CLAUDE_CONFIG_DIR):
//        commands/<x>.md   one per opencode command (it @-includes .ai/commands/<x>.md; a subtask names its subagent)
//        agents/<x>.md     one per opencode agent (description, tools: no Edit/Write when the agent may not edit)
//        settings.json     the hooks (ticket header, state after a compaction, edits in your diary) — and with
//                          --with-permissions the permission baseline (git writes denied, the tools allowed)
//        .ai-methodology.json   what was installed, to update or remove exactly that
//   node .ai/scripts/ai.mjs claude project     this project's CLAUDE.md: only @-imports of the always-loaded files
//        (.ai/non-negotiables.md, .ai/orchestrator.md, .ai/rules/*.md, .ai/claude-code.md). In a repository it is
//        added to .git/info/exclude: nothing enters the client's git. A CLAUDE.md that is not ours is never touched.
//   node .ai/scripts/ai.mjs claude project --remove   the project no longer uses Claude Code: our CLAUDE.md goes
//   node .ai/scripts/ai.mjs claude check       for doctor: installed, its version, the project's CLAUDE.md
//   node .ai/scripts/ai.mjs claude uninstall   removes exactly what install wrote (the hooks and permissions too)
// Files we did not write are never overwritten. Idempotent.
import { spawnSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"
import { AI, WORKSPACE } from "./project.ts"

const SRC = join(AI, "install", "opencode")
const VERSION = (() => { try { return readFileSync(join(AI, "install", "VERSION"), "utf-8").trim() } catch { return "?" } })()
export const claudeDir = () => process.env.CLAUDE_CONFIG_DIR || join(homedir(), ".claude")
const MANIFEST = () => join(claudeDir(), ".ai-methodology.json")
const MARK = "<!-- ai-core: generated by `node .ai/scripts/ai.mjs claude` — edit the sources in .ai/, not this file -->"
const HOOK = (k: string) => `cd "$CLAUDE_PROJECT_DIR" 2>/dev/null && [ -f .ai/scripts/ai.mjs ] && node .ai/scripts/ai.mjs hook ${k} || true`
const ours = (h: unknown) => JSON.stringify(h).includes(".ai/scripts/ai.mjs hook ")

type Manifest = { version: string; files: string[]; permissions?: { allow: string[]; deny: string[]; ask: string[] } }
const readJson = (f: string, d: any) => { try { return JSON.parse(readFileSync(f, "utf-8")) } catch { return d } }

/** the front matter of an opencode file: its simple keys, the permission block as text, and the body */
function parse(text: string): { meta: Record<string, string>; perm: string; body: string } {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!m) return { meta: {}, perm: "", body: text }
  const meta: Record<string, string> = {}
  for (const l of m[1].split("\n")) { const k = l.match(/^([\w-]+):\s*(.*)$/); if (k && k[2]) meta[k[1]] = k[2].trim() }
  return { meta, perm: m[1].slice(m[1].indexOf("permission:") >= 0 ? m[1].indexOf("permission:") : m[1].length), body: m[2] }
}

/** what Claude Code gets: path under ~/.claude → content */
export function expected(): Map<string, string> {
  const out = new Map<string, string>()
  const cdir = join(SRC, "commands"), adir = join(SRC, "agents")
  for (const f of existsSync(cdir) ? readdirSync(cdir).filter((x) => x.endsWith(".md")).sort() : []) {
    const { meta, body } = parse(readFileSync(join(cdir, f), "utf-8"))
    const bangs = [...body.matchAll(/^!`([^`]+)`/gm)].map((x) => `Bash(${x[1]})`)
    const fm = [`description: ${meta.description ?? f.replace(/\.md$/, "")}`, ...(bangs.length ? [`allowed-tools: ${[...new Set(bangs)].join(", ")}`] : [])]
    const sub = meta.subtask === "true" && meta.agent
      ? `Run this procedure through the \`${meta.agent}\` subagent (Task tool, subagent_type \`${meta.agent}\`): give it the procedure file below and the arguments, then relay its report once.\n\n` : ""
    out.set(`commands/${f}`, `---\n${fm.join("\n")}\n---\n${MARK}\n${sub}${body.replace(/^\n+/, "")}`)
  }
  for (const f of existsSync(adir) ? readdirSync(adir).filter((x) => x.endsWith(".md")).sort() : []) {
    const name = f.replace(/\.md$/, "")
    const { meta, perm, body } = parse(readFileSync(join(adir, f), "utf-8"))
    const readOnly = /^\s+edit:\s*deny/m.test(perm)
    const fm = [`name: ${name}`, `description: ${meta.description ?? name}`, ...(readOnly ? ["tools: Read, Grep, Glob, Bash"] : [])]
    out.set(`agents/${f}`, `---\n${fm.join("\n")}\n---\n${MARK}\n${body.replace(/^\n+/, "")}`)
  }
  return out
}

/** opencode's bash permission globs → Claude Code rules ("git commit*" → Bash(git commit:*)) */
function baseline(): { allow: string[]; deny: string[]; ask: string[] } {
  const p = readJson(join(SRC, "opencode.global.json"), {}).permission?.bash ?? {}
  const out = { allow: ["Bash(node .ai/scripts/ai.mjs:*)"], deny: ["Read(./.env)", "Read(./.env.*)", "Read(**/*.key)", "Read(**/*.pem)"], ask: [] as string[] }
  for (const [g, v] of Object.entries<string>(p)) {
    if (g === "*" || /^\*|\*.+\*/.test(g)) continue   // "anything" and "contains" globs have no Claude Code rule
    const rule = g.endsWith("*") ? `Bash(${g.replace(/\s*\*+$/, "")}:*)` : `Bash(${g})`
    ;(out as any)[v]?.push(rule)
  }
  for (const k of ["allow", "deny", "ask"] as const) out[k] = [...new Set(out[k])]
  return out
}

function settings(add: boolean, perms: Manifest["permissions"] | null, drop: Manifest["permissions"] | undefined): void {
  const file = join(claudeDir(), "settings.json"), cur = readJson(file, {})
  cur.hooks ??= {}
  for (const ev of Object.keys(cur.hooks)) { cur.hooks[ev] = (cur.hooks[ev] as unknown[]).filter((h) => !ours(h)); if (!cur.hooks[ev].length) delete cur.hooks[ev] }
  if (add) {
    const put = (ev: string, h: unknown) => (cur.hooks[ev] = [...(cur.hooks[ev] ?? []), h])
    put("UserPromptSubmit", { hooks: [{ type: "command", command: HOOK("prompt"), timeout: 20 }] })
    put("SessionStart", { hooks: [{ type: "command", command: HOOK("session"), timeout: 20 }] })
    put("PostToolUse", { matcher: "Edit|Write|MultiEdit", hooks: [{ type: "command", command: HOOK("edit"), timeout: 120 }] })
  }
  if (!Object.keys(cur.hooks).length) delete cur.hooks
  if (drop) for (const k of ["allow", "deny", "ask"] as const) if (cur.permissions?.[k]) cur.permissions[k] = cur.permissions[k].filter((r: string) => !drop[k].includes(r))
  if (perms) { cur.permissions ??= {}; for (const k of ["allow", "deny", "ask"] as const) cur.permissions[k] = [...new Set([...(cur.permissions[k] ?? []), ...perms[k]])] }
  if (cur.permissions) for (const k of Object.keys(cur.permissions)) if (Array.isArray(cur.permissions[k]) && !cur.permissions[k].length) delete cur.permissions[k]
  if (cur.permissions && !Object.keys(cur.permissions).length) delete cur.permissions
  mkdirSync(claudeDir(), { recursive: true })
  if (existsSync(file)) writeFileSync(`${file}.bak-ai`, readFileSync(file))
  writeFileSync(file, JSON.stringify(cur, null, 2) + "\n")
}

function install(withPerms: boolean): number {
  const dir = claudeDir(), man: Manifest = readJson(MANIFEST(), { version: "", files: [] })
  const want = expected(), done: string[] = [], kept: string[] = []
  for (const f of man.files.filter((f) => !want.has(f))) rmSync(join(dir, f), { force: true })   // retired by this version
  for (const [rel, text] of want) {
    const p = join(dir, rel)
    if (existsSync(p) && !man.files.includes(rel) && !readFileSync(p, "utf-8").includes(MARK)) { kept.push(rel); continue }   // the user's own
    mkdirSync(join(p, ".."), { recursive: true }); writeFileSync(p, text); done.push(rel)
  }
  // the baseline: asked now, or kept from an earlier install that added it (refreshed to this version's rules)
  const perms = withPerms || man.permissions ? baseline() : null
  settings(true, perms, man.permissions)
  writeFileSync(MANIFEST(), JSON.stringify({ version: VERSION, files: done, ...(perms ? { permissions: perms } : {}) }, null, 2) + "\n")
  console.log(`✔ Claude Code wiring ${VERSION} → ${dir}`)
  console.log(`  ${done.filter((f) => f.startsWith("commands/")).length} commands, ${done.filter((f) => f.startsWith("agents/")).length} agents, hooks (ticket header, state after a compaction, edits in your diary)${perms ? ", permission baseline" : ""}`)
  for (const k of kept) console.log(`  ⚠ ${k} exists and is not ours — left as it is`)
  return 0
}

function uninstall(): number {
  const dir = claudeDir(), man: Manifest = readJson(MANIFEST(), { version: "", files: [] })
  for (const f of man.files) rmSync(join(dir, f), { force: true })
  if (existsSync(join(dir, "settings.json"))) settings(false, null, man.permissions)
  rmSync(MANIFEST(), { force: true })
  console.log(`✔ Claude Code wiring removed from ${dir} (${man.files.length} files, the hooks${man.permissions ? ", the permission baseline" : ""})`)
  return 0
}

/** the project's CLAUDE.md: @-imports of what opencode loads through its instructions */
export function projectFile(): string {
  let rules: string[] = []
  try { rules = readdirSync(join(AI, "rules")).filter((f) => f.endsWith(".md")).sort().map((f) => `@.ai/rules/${f}`) } catch { /* none */ }
  return [MARK, "", "@.ai/non-negotiables.md", "@.ai/orchestrator.md", ...rules, "@.ai/claude-code.md", ""].join("\n")
}

function project(remove = false): number {
  const f = join(WORKSPACE, "CLAUDE.md"), text = projectFile()
  if (remove) {   // the project no longer uses Claude Code: our CLAUDE.md goes, one that is not ours stays
    if (existsSync(f) && readFileSync(f, "utf-8").includes(MARK)) { rmSync(f); console.log("✔ CLAUDE.md removed — this project no longer uses Claude Code") }
    return 0
  }
  if (existsSync(f) && !readFileSync(f, "utf-8").includes(MARK)) {
    console.log(`⚠ ${f} exists and is not ours — left as it is. Add these lines to it so Claude Code loads the rules:`)
    for (const l of text.split("\n").filter((l) => l.startsWith("@"))) console.log(`    ${l}`)
    return 0
  }
  const was = existsSync(f) ? readFileSync(f, "utf-8") : ""
  if (was !== text) writeFileSync(f, text)
  // a repository never sees it: a local exclude (its .gitignore untouched)
  const git = (...a: string[]) => spawnSync("git", ["-C", WORKSPACE, ...a], { encoding: "utf-8" })
  if (git("rev-parse", "--is-inside-work-tree").stdout?.trim() === "true" && git("check-ignore", "-q", "CLAUDE.md").status !== 0
    && git("ls-files", "--error-unmatch", "CLAUDE.md").status !== 0) {
    let ex = git("rev-parse", "--git-path", "info/exclude").stdout.trim()
    if (!ex.startsWith("/")) ex = join(WORKSPACE, ex)
    mkdirSync(join(ex, ".."), { recursive: true })
    writeFileSync(ex, (existsSync(ex) ? readFileSync(ex, "utf-8").replace(/\n?$/, "\n") : "") + "CLAUDE.md\n")
  }
  console.log(`✔ CLAUDE.md ${was === text ? "up to date" : was ? "updated" : "written"} — Claude Code loads .ai/non-negotiables.md, the orchestrator, the rules and .ai/claude-code.md`)
  return 0
}

/** for doctor: [status, detail, fix?] */
export function check(): [string, string, string?] {
  const man = readJson(MANIFEST(), null)
  if (!man) return ["FAIL", `Claude Code wiring not installed (${claudeDir()})`, "node .ai/scripts/ai.mjs claude install"]
  const missing = [...expected().keys()].filter((f) => !existsSync(join(claudeDir(), f)))
  const hooks = JSON.stringify(readJson(join(claudeDir(), "settings.json"), {}).hooks ?? {})
  const f = join(WORKSPACE, "CLAUDE.md"), cm = existsSync(f) ? readFileSync(f, "utf-8") : ""
  if (missing.length || !hooks.includes(".ai/scripts/ai.mjs hook ")) return ["FAIL", `Claude Code wiring incomplete: ${missing.length ? missing.slice(0, 3).join(", ") : "the hooks"}`, "node .ai/scripts/ai.mjs claude install"]
  if (!cm.includes("@.ai/non-negotiables.md")) return ["FAIL", "no CLAUDE.md importing .ai/ in the project folder — Claude Code does not load the rules", "node .ai/scripts/ai.mjs claude project"]
  if (cm.includes(MARK) && cm !== projectFile()) return ["WARN", "CLAUDE.md does not import the current rules", "node .ai/scripts/ai.mjs claude project"]
  if (man.version !== VERSION) return ["WARN", `Claude Code wiring ${man.version}, .ai ships ${VERSION}`, "node .ai/scripts/ai.mjs claude install"]
  return ["OK", `${[...expected().keys()].filter((k) => k.startsWith("commands/")).length} commands, ${[...expected().keys()].filter((k) => k.startsWith("agents/")).length} agents, hooks in ${claudeDir().replace(homedir(), "~")}; CLAUDE.md imports .ai/`]
}

export function main(argv: string[]): number {
  const [cmd] = argv
  if (cmd === "install") return install(argv.includes("--with-permissions"))
  if (cmd === "uninstall") return uninstall()
  if (cmd === "project") return project(argv.includes("--remove"))
  if (cmd === "check") { const [s, d, fix] = check(); console.log(`${s} ${d}${fix ? ` — ${fix}` : ""}`); return s === "FAIL" ? 1 : 0 }
  console.error("usage: node .ai/scripts/ai.mjs claude install [--with-permissions] | project | check | uninstall")
  return 2
}
