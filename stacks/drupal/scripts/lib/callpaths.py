#!/usr/bin/env python3
"""callpaths.py — generated call paths and related skills for every business skill.

1. Indexes the PHP code of lib/ (classes, methods, procedural functions, declared return types) and the
   calls inside each function body, resolved by receiver when possible:
     $this->x()                       → same class
     ->getFormsHelper()->x()          → class of getFormsHelper()'s declared return type
     $this->formsHelper->x()          → class named like the property (FormsHelper)
     Class::x()                       → that class
     ->x() / x()                      → the only class (or procedural function) defining x
2. For each skill, starts from the methods it cites (Key files + `Class::method()` in its text) and writes the
   callees, two levels deep, into a generated `## Call path` section — the "stack trace" of the flow.
3. Writes `related_skills: [...]` in each skill's front matter + a generated `## Related skills` section:
   skills that share a method, or a non-shared-helper file, with this skill's Key files or call path.

Run through the wrapper:  bash .ai/scripts/knowledge/scan-callpaths.sh [--update]
Without --update it only reports which skills would change (like the other scanners). Standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import impact  # noqa: E402

ROOT = impact.ROOT
LIB = ROOT / "lib"
SRC_EXT = {".php", ".module", ".inc", ".theme", ".install"}
DEPTH = 2
MAX_CHILDREN = 6
MAX_LINES = 70
SEEDS_PER_FILE = 3
ENTRY_RE = re.compile(r"^(submitForm|buildForm|validateForm|build|blockAccess|access|on[A-Z]\w*|alter\w*|process\w*|handle\w*|execute|__invoke)$")
COMMON_PREFIX = re.compile(r"^(get|set|is|has|add|load|save|to|create|delete|update|apply|check)[A-Z]")
MAX_RELATED = 8

CLASS_RE = re.compile(r"^\s*(?:abstract\s+|final\s+)*(?:class|trait|interface)\s+([A-Za-z_][A-Za-z0-9_]*)")
FUNC_RE = re.compile(r"^\s*(?:(?:public|protected|private|static|abstract|final)\s+)*function\s+&?([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)$")
RET_RE = re.compile(r"\)\s*:\s*\??\\?([A-Za-z_][A-Za-z0-9_\\]*)")
CALL_RE = re.compile(r"(?P<recv>\$this->[A-Za-z_][A-Za-z0-9_]*->|\$this->|->[A-Za-z_][A-Za-z0-9_]*\(\)->|->|(?P<cls>[A-Z][A-Za-z0-9_]*)::|(?<![\w>$:\\]))(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*\(")
SKIP = {"t", "get", "set", "load", "save", "create", "id", "bundle", "value", "isset", "empty", "array", "count",
        "in_array", "is_array", "array_merge", "array_keys", "array_map", "array_filter", "implode", "explode",
        "sprintf", "strtolower", "trim", "reset", "end", "key", "__construct", "getValue", "setValue", "hasField",
        "getStorage", "getQuery", "condition", "execute", "accessCheck", "range", "sort", "loadMultiple",
        "getEntityTypeManager", "toString", "getString", "label", "access", "render", "build", "submitForm",
        "buildForm", "validateForm", "getFormId", "getSubscribedEvents", "isNew", "getTranslation", "hasTranslation"}

FILE_FUNCS: dict[str, list] = {}
GRAPH = impact.AI_DIR / "context" / "callgraph.json"
SHORT_HOPS = 3
SHORT_MAX = 10
SHORT_INTRO = ("Main path of each entry point (distinctive calls only). Full call tree, callers and files: "
               "`.ai/context/callgraph.json` — used by `/impact`. Edit the lines below freely: "
               "a hand-edited block is never overwritten.")


def digest(text: str) -> str:
    return hashlib.sha1(text.strip().encode("utf-8")).hexdigest()[:12]
DISPLAY: dict[tuple, str] = {}

BEGIN_CP = "<!-- call-path:begin — generated by `bash .ai/scripts/knowledge/scan-callpaths.sh --update`; hand edits are kept -->"
END_CP = "<!-- call-path:end -->"
BEGIN_RS = "<!-- related-skills:begin — generated by `bash .ai/scripts/knowledge/scan-callpaths.sh --update` -->"
END_RS = "<!-- related-skills:end -->"


@dataclass
class Func:
    cls: str | None
    name: str
    path: str
    line: int
    ret: str | None = None
    body: list[str] = field(default_factory=list)

    @property
    def label(self) -> str:
        return f"{self.cls}::{self.name}()" if self.cls else f"{self.name}()"


def index_code():
    funcs: list[Func] = []
    for p in sorted(LIB.rglob("*")):
        if p.suffix not in SRC_EXT or "node_modules" in p.parts or not p.is_file():
            continue
        rel = str(p.relative_to(ROOT))
        cls = None
        cur: Func | None = None
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if (m := CLASS_RE.match(line)):
                cls = m.group(1)
            if (m := FUNC_RE.match(line)):
                r = RET_RE.search(line)
                cur = Func(cls if p.suffix == ".php" else None, m.group(1), rel, i,
                           r.group(1).split("\\")[-1] if r else None)
                funcs.append(cur)
                continue
            if cur is not None:
                cur.body.append(line)
    FILE_FUNCS.clear()
    for f in funcs:
        FILE_FUNCS.setdefault(f.path, []).append(f)
    by_name: dict[str, list[Func]] = defaultdict(list)
    by_key: dict[tuple, Func] = {}
    for f in funcs:
        by_name[f.name].append(f)
        by_key[(f.cls, f.name)] = f
    return funcs, by_name, by_key


def is_trivial(f: Func) -> bool:
    """Plain accessors (GlobalService::getFormsHelper() …) add noise, not flow."""
    code = [l.strip() for l in f.body if l.strip() and not l.strip().startswith(("*", "/", "}"))]
    return len(code) <= 2 and any(l.startswith("return $this->") and "(" not in l for l in code)


def lc_first(s: str) -> str:
    return s[:1].lower() + s[1:]


def callees(f: Func, by_name, by_key) -> list[Func]:
    out: list[Func] = []
    seen = set()
    getter_ret = {}
    for line in f.body:
        stripped = line.lstrip()
        if stripped.startswith(("*", "/*", "#")):
            continue  # docblocks and comments (incl. the docblock of the NEXT function, which sits in this body)
        code = line.split("//", 1)[0]
        for m in CALL_RE.finditer(code):
            name, recv, cls = m.group("name"), m.group("recv") or "", m.group("cls")
            if name in SKIP or name.startswith("assert"):
                continue
            target = None
            if cls and cls not in ("self", "static", "parent"):
                target = by_key.get((cls, name))
            elif recv == "$this->" or cls in ("self", "static"):
                target = by_key.get((f.cls, name))
            elif recv.startswith("$this->") and recv.endswith("->"):  # $this->prop->name(
                prop = recv[len("$this->"):-2]
                target = by_key.get((prop[:1].upper() + prop[1:], name))
            elif recv.startswith("->") and recv.endswith("()->"):     # ->getX()->name(
                getter = recv[2:-4]
                ret = getter_ret.get(getter)
                if ret is None:
                    cands = [g.ret for g in by_name.get(getter, []) if g.ret]
                    ret = getter_ret[getter] = cands[0] if cands else ""
                if ret:
                    target = by_key.get((ret, name))
            distinctive = len(name) >= 14 or not COMMON_PREFIX.match(name)
            if target is None and recv == "" and not cls:
                cands = [c for c in by_name.get(name, []) if c.cls is None]
                if len(cands) == 1:
                    target = cands[0]
            if target is None and recv.endswith("->") and not cls and distinctive:
                cands = [c for c in by_name.get(name, []) if c.cls]
                if len(cands) == 1:
                    target = cands[0]
            if target is not None and is_trivial(target):
                continue
            if target is not None and target is not f and target.label not in seen:
                seen.add(target.label)
                out.append(target)
    return out


def tree(seed: Func, by_name, by_key, lines: list[str], files: set[str], methods: set[tuple]):
    def walk(f: Func, depth: int, indent: str, path: set[str]):
        if len(lines) >= MAX_LINES:
            return
        files.add(f.path)
        methods.add((f.cls, f.name.lower()))
        DISPLAY[(f.cls, f.name.lower())] = f.label
        lines.append(f"{indent}- `{f.label}`")
        if depth >= DEPTH:
            return
        kids = [k for k in callees(f, by_name, by_key) if k.label not in path]
        for k in kids[:MAX_CHILDREN]:
            walk(k, depth + 1, indent + "  ", path | {k.label})
        if len(kids) > MAX_CHILDREN and len(lines) < MAX_LINES:
            lines.append(f"{indent}  - … {len(kids) - MAX_CHILDREN} more")
    walk(seed, 0, "", {seed.label})


def strip_generated(text: str) -> str:
    text = re.sub(re.escape(BEGIN_CP) + r".*?" + re.escape(END_CP), "", text, flags=re.S)
    return re.sub(re.escape(BEGIN_RS) + r".*?" + re.escape(END_RS), "", text, flags=re.S)


def seeds_for(skill: impact.Doc, by_key, by_name) -> list[Func]:
    seeds, seen = [], set()
    text = skill.path.read_text(encoding="utf-8")
    text = strip_generated(text)  # never seed from our own output
    order = [(c, m) for c, m in impact.CLASS_METHOD_RE.findall(text)]
    keyfiles = impact.section(text, "Key files")
    for line in keyfiles.splitlines():
        paths = [x for x in impact.PATH_RE.findall(line) if Path(x).suffix in SRC_EXT]
        if not paths:
            continue
        cls = Path(paths[0]).stem
        cited = []
        for tok in impact.BACKTICK_RE.findall(line):
            mm = impact.METHOD_TOKEN_RE.match(tok.strip())
            if mm:
                cited.append((cls, mm.group(1)))
        if not cited:  # no method named on this line: start from the entry points of the file
            fpath = paths[0]
            entries = [f for f in FILE_FUNCS.get(fpath, []) if ENTRY_RE.match(f.name)]
            cited = [(f.cls, f.name) for f in entries[:SEEDS_PER_FILE]]
        order.extend(cited)
    for cls, name in order:
        f = by_key.get((cls, name))
        if f is None:
            procedural = [x for x in by_name.get(name, []) if x.cls is None]
            f = procedural[0] if len(procedural) == 1 else None
        if f and f.label not in seen and f.name not in {"__construct", "create", "getFormId", "getSubscribedEvents"}:
            seen.add(f.label)
            seeds.append(f)
    return seeds


def replace_block(text: str, heading: str, begin: str, end: str, content: str, before: str | None) -> str:
    block = f"{heading}\n\n{begin}\n{content}\n{end}\n"
    pattern = re.compile(rf"(?ms)^{re.escape(heading)}\n\n{re.escape(begin)}.*?{re.escape(end)}\n")
    if pattern.search(text):
        return pattern.sub(lambda _: block, text, count=1)
    if before and (m := re.search(rf"(?m)^{re.escape(before)}\b", text)):
        return text[:m.start()] + block + "\n" + text[m.start():]
    return text.rstrip() + "\n\n" + block


def set_front_matter(text: str, key: str, value: str) -> str:
    m = impact.FM_RE.match(text)
    if not m:
        return text
    fm = m.group(1)
    if re.search(rf"(?m)^{key}:", fm):
        fm = re.sub(rf"(?m)^{key}:.*$", f"{key}: {value}", fm, count=1)
    else:
        fm = fm + f"\n{key}: {value}"
    return f"---\n{fm}\n---\n" + text[m.end():]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--update", action="store_true", help="write the sections and front matter into the skills")
    ap.add_argument("--show", metavar="SKILL", help="print the generated call path of one skill")
    a = ap.parse_args()

    funcs, by_name, by_key = index_code()
    skills = impact.load_skills()  # also computes impact.HUBS
    # Recompute each skill's own references WITHOUT the generated blocks, so a second run is stable.
    for s in skills:
        raw = strip_generated(s.path.read_text(encoding="utf-8"))
        own = impact.Doc("skill", s.key, s.title, s.path)
        impact.harvest_code_refs(own, raw, keyfile_text=impact.section(raw, "Key files"))
        s.files, s.class_methods = own.files, own.class_methods
    per_skill: dict[str, dict] = {}
    for s in skills:
        lines, files, methods = [], set(), set()
        for seed in seeds_for(s, by_key, by_name):
            if len(lines) >= MAX_LINES:
                lines.append(f"- … truncated at {MAX_LINES} lines")
                break
            tree(seed, by_name, by_key, lines, files, methods)
        keyfiles = {f for f in s.files if not f.endswith("/")}
        per_skill[s.key] = dict(doc=s, lines=lines, files=files | keyfiles,
                                methods={(c, m) for c, m in methods} | {(c, m) for c, m in s.class_methods})

    # Utilities used by many flows (isAdmin(), getCurrentStep() …) do not make two flows related.
    freq: dict[tuple, int] = defaultdict(int)
    ffreq: dict[str, int] = defaultdict(int)
    for d in per_skill.values():
        for mth in d["methods"]:
            freq[mth] += 1
        for fl in d["files"]:
            ffreq[fl] += 1
    COMMON = 5
    for d in per_skill.values():
        d["rel_methods"] = {mth for mth in d["methods"] if freq[mth] <= COMMON}
        d["rel_files"] = {fl for fl in d["files"] if ffreq[fl] <= COMMON}

    related: dict[str, list[tuple[str, list[str]]]] = {}
    for a_key, a_d in per_skill.items():
        rows = []
        for b_key, b_d in per_skill.items():
            if a_key == b_key:
                continue
            shared_m = sorted({DISPLAY.get((c, m), f"{c}::{m}()") for c, m in a_d["rel_methods"] & b_d["rel_methods"] if c})
            shared_f = sorted(Path(f).name for f in a_d["rel_files"] & b_d["rel_files"]
                              if Path(f).stem not in impact.HUBS and Path(f).name not in {Path(x.split('::')[0]).name for x in shared_m})
            if shared_m or shared_f:
                rows.append((b_key, len(shared_m) * 2 + len(shared_f), shared_m, shared_f))
        rows.sort(key=lambda r: (-r[1], r[0]))
        related[a_key] = [(k, m + f) for k, _, m, f in rows[:MAX_RELATED]]

    # ── Short call path for the LLM: one line per entry point, distinctive callees only ──
    def short_line(seed: Func) -> str:
        chain, cur, seen = [f"`{seed.label}`"], seed, {seed.label}
        for _ in range(SHORT_HOPS):
            nxt = None
            for k in callees(cur, by_name, by_key):
                if k.label in seen or freq[(k.cls, k.name.lower())] > COMMON:
                    continue
                nxt = k
                break
            if nxt is None:
                break
            seen.add(nxt.label)
            chain.append(f"`{nxt.name}()`" if nxt.cls == cur.cls else f"`{nxt.label}`")
            cur = nxt
        return "- " + " → ".join(chain)

    for key, d in per_skill.items():
        out, seen_lines = [], set()
        seeds = seeds_for(d["doc"], by_key, by_name)
        cited = {(c, m.lower()) for c, m in d["doc"].class_methods}

        def priority(f: Func) -> int:
            if (f.cls, f.name.lower()) in cited:
                return 0                      # named in the skill text
            if re.match(r"^(submitForm|on[A-Z]|handle|alter|process|execute|__invoke)", f.name):
                return 1                      # changes state
            if f.name in ("build", "buildForm", "validateForm", "blockAccess", "access"):
                return 3                      # renders / checks
            return 2
        for seed in sorted(seeds, key=lambda f: (priority(f), seeds.index(f))):
            line = short_line(seed)
            if line not in seen_lines:
                seen_lines.add(line)
                out.append(line)
            if len(out) >= SHORT_MAX:
                break
        d["short"] = out

    if a.show:
        d = per_skill.get(a.show)
        if not d:
            sys.exit(f"unknown skill {a.show}")
        print("SHORT (in SKILL.md):")
        print("\n".join(d["short"]) or "(no seed method found)")
        print(f"\nFULL (in {GRAPH.relative_to(impact.AI_DIR.parent)}): {len(d['lines'])} lines, {len(d['files'])} files")
        print("\nrelated_skills:", [k for k, _ in related[a.show]])
        for k, why in related[a.show]:
            print(f"  {k}: {', '.join(why[:5])}")
        return 0

    old_graph = {}
    if GRAPH.is_file():
        try:
            old_graph = json.loads(GRAPH.read_text(encoding="utf-8")).get("skills", {})
        except ValueError:
            old_graph = {}

    graph = {"generated_by": "bash .ai/scripts/knowledge/scan-callpaths.sh --update", "depth": DEPTH, "functions_indexed": len(funcs), "skills": {}}
    changed, kept = 0, []
    for key, d in per_skill.items():
        s = d["doc"]
        text = s.path.read_text(encoding="utf-8")
        short = "\n".join(d["short"]) if d["short"] else "- (no method of this skill could be resolved in lib/ — cite `Class::method()` in Key files)"
        current = re.search(re.escape(BEGIN_CP) + r"\n(.*?)\n" + re.escape(END_CP), text, re.S)
        current_body = current.group(1).split("\n\n", 1)[-1] if current else None
        prev_hash = old_graph.get(key, {}).get("short_hash")
        if current_body is not None and prev_hash and digest(current_body) != prev_hash and current_body.strip() != short.strip() \
                and not current_body.startswith("Generated from the methods"):
            short = current_body  # edited by hand: keep it
            kept.append(key)
        cp = SHORT_INTRO + "\n\n" + short
        new = replace_block(text, "## Call path", BEGIN_CP, END_CP, cp, "## Key files")
        new = re.sub(r"(?ms)^## Related skills\n\n" + re.escape(BEGIN_RS) + r".*?" + re.escape(END_RS) + r"\n\n?", "", new)
        new = set_front_matter(new, "related_skills", "[" + ", ".join(k for k, _ in related[key]) + "]")
        graph["skills"][key] = {
            "entries": [l[2:] for l in d["short"]],
            "tree": d["lines"],
            "files": sorted(f for f in d["files"] if Path(f).suffix in SRC_EXT),
            "methods": sorted(DISPLAY.get((c, m), f"{c}::{m}()") for c, m in d["methods"] if c),
            "related": [{"skill": k, "shares": why} for k, why in related[key]],
            "short_hash": digest(short),
        }
        if new != text:
            changed += 1
            if a.update:
                s.path.write_text(new, encoding="utf-8")
            else:
                print(f"STALE {key}")
    graph_text = json.dumps(graph, indent=1, ensure_ascii=False) + "\n"
    graph_stale = not GRAPH.is_file() or GRAPH.read_text(encoding="utf-8") != graph_text
    if a.update:
        GRAPH.write_text(graph_text, encoding="utf-8")
        print(f"Call paths written: {changed} skill(s) changed, graph {GRAPH.name} ({len(funcs)} functions indexed).")
        if kept:
            print("Hand-edited call paths kept (not regenerated): " + ", ".join(kept))
    else:
        if graph_stale:
            print(f"STALE {GRAPH.name}")
        print("NO CHANGES — call paths, related skills and the call graph are up to date." if not changed and not graph_stale
              else "Out of date — run: bash .ai/scripts/knowledge/scan-callpaths.sh --update")
    return 0


if __name__ == "__main__":
    sys.exit(main())
