// callpaths.ts — generated call paths and related skills for every business skill.
// 1. Indexes the PHP code of lib/ (classes, methods, procedural functions, declared return types) and the calls inside
//    each function body, resolved by receiver when possible ($this->x(), ->getX()->x(), $this->prop->x(), Class::x(),
//    or the only class / procedural function defining x).
// 2. For each skill, starts from the methods it cites (Key files + `Class::method()` in its text) and writes the
//    callees, two levels deep, into a generated `## Call path` section — the "stack trace" of the flow.
// 3. Writes `related_skills: [...]` in each skill's front matter: skills that share a method, or a non-shared-helper
//    file, with this skill's Key files or call path.
//   node .ai/scripts/cli.ts callpaths [--update] [--show SKILL]      (wrapper: bash .ai/scripts/knowledge/scan-callpaths.sh)
import { createHash } from "node:crypto"
import { writeFileSync } from "node:fs"
import * as impact from "./impact.ts"
import { ROOT, walkCode } from "./project.ts"
import { cmp, dumps, escapeRe, isFile, read, splitlines } from "./util.ts"

export const SRC_EXT = [".php", ".module", ".inc", ".theme", ".install"]
const DEPTH = 2, MAX_CHILDREN = 6, MAX_LINES = 70, SEEDS_PER_FILE = 3, MAX_RELATED = 8, SHORT_HOPS = 3, SHORT_MAX = 10, COMMON = 5
const ENTRY_RE = /^(submitForm|buildForm|validateForm|build|blockAccess|access|on[A-Z]\w*|alter\w*|process\w*|handle\w*|execute|__invoke)$/
const COMMON_PREFIX = /^(get|set|is|has|add|load|save|to|create|delete|update|apply|check)[A-Z]/
const CLASS_RE = /^\s*(?:abstract\s+|final\s+)*(?:class|trait|interface)\s+([A-Za-z_][A-Za-z0-9_]*)/
const FUNC_RE = /^\s*(?:(?:public|protected|private|static|abstract|final)\s+)*function\s+&?([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)$/
const RET_RE = /\)\s*:\s*\??\\?([A-Za-z_][A-Za-z0-9_\\]*)/
const CALL_RE = /(?<recv>\$this->[A-Za-z_][A-Za-z0-9_]*->|\$this->|->[A-Za-z_][A-Za-z0-9_]*\(\)->|->|(?<cls>[A-Z][A-Za-z0-9_]*)::|(?<![\w>$:\\]))(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*\(/g
const SKIP = new Set(["t", "get", "set", "load", "save", "create", "id", "bundle", "value", "isset", "empty", "array", "count",
  "in_array", "is_array", "array_merge", "array_keys", "array_map", "array_filter", "implode", "explode",
  "sprintf", "strtolower", "trim", "reset", "end", "key", "__construct", "getValue", "setValue", "hasField",
  "getStorage", "getQuery", "condition", "execute", "accessCheck", "range", "sort", "loadMultiple",
  "getEntityTypeManager", "toString", "getString", "label", "access", "render", "build", "submitForm",
  "buildForm", "validateForm", "getFormId", "getSubscribedEvents", "isNew", "getTranslation", "hasTranslation"])
const GRAPH = `${impact.AI_DIR}/context/callgraph.json`
const SHORT_INTRO = "Main path of each entry point (distinctive calls only). Full call tree, callers and files: " +
  "`.ai/context/callgraph.json` — used by `/impact`. Edit the lines below freely: a hand-edited block is never overwritten."
const BEGIN_CP = "<!-- call-path:begin — generated by `bash .ai/scripts/knowledge/scan-callpaths.sh --update`; hand edits are kept -->"
const END_CP = "<!-- call-path:end -->"
const BEGIN_RS = "<!-- related-skills:begin — generated by `bash .ai/scripts/knowledge/scan-callpaths.sh --update` -->"
const END_RS = "<!-- related-skills:end -->"

const sha1 = (text: string) => createHash("sha1").update(text.trim(), "utf8").digest("hex").slice(0, 12)
/** a (cls, name) tuple as a Map key; cls null ≠ "None" */
export const tk = (cls: string | null, name: string) => `${cls === null ? "\u0001" : cls}\u0000${name}`
const untk = (k: string): [string | null, string] => { const [c, n] = k.split("\u0000"); return [c === "\u0001" ? null : c, n] }

export class Func {
  cls: string | null; name: string; path: string; line: number; ret: string | null; body: string[] = []
  constructor(cls: string | null, name: string, path: string, line: number, ret: string | null) { this.cls = cls; this.name = name; this.path = path; this.line = line; this.ret = ret }
  get label() { return this.cls ? `${this.cls}::${this.name}()` : `${this.name}()` }
}

const FILE_FUNCS = new Map<string, Func[]>()
const DISPLAY = new Map<string, string>()
export type ByName = Map<string, Func[]>
export type ByKey = Map<string, Func>

export function indexCode(): [Func[], ByName, ByKey] {
  const funcs: Func[] = []
  for (const p of walkCode((x) => SRC_EXT.includes(impact.psuffix(x)) && !x.split("/").includes("node_modules"))) {
    const rel = p.slice(ROOT.length + 1), isPhp = impact.psuffix(p) === ".php"
    let cls: string | null = null, cur: Func | null = null
    splitlines(read(p)).forEach((line, i) => {
      const c = line.match(CLASS_RE)
      if (c) cls = c[1]
      const m = line.match(FUNC_RE)
      if (m) {
        const r = line.match(RET_RE)
        cur = new Func(isPhp ? cls : null, m[1], rel, i + 1, r ? r[1].split("\\").pop()! : null)
        funcs.push(cur)
        return
      }
      if (cur) cur.body.push(line)
    })
  }
  FILE_FUNCS.clear()
  for (const f of funcs) FILE_FUNCS.set(f.path, [...(FILE_FUNCS.get(f.path) ?? []), f])
  const byName: ByName = new Map(), byKey: ByKey = new Map()
  for (const f of funcs) { byName.set(f.name, [...(byName.get(f.name) ?? []), f]); byKey.set(tk(f.cls, f.name), f) }
  return [funcs, byName, byKey]
}

/** Plain accessors (GlobalService::getFormsHelper() …) add noise, not flow. */
function isTrivial(f: Func): boolean {
  const code = f.body.map((l) => l.trim()).filter((l) => l && !["*", "/", "}"].some((x) => l.startsWith(x)))
  return code.length <= 2 && code.some((l) => l.startsWith("return $this->") && !l.includes("("))
}

export function callees(f: Func, byName: ByName, byKey: ByKey): Func[] {
  const out: Func[] = [], seen = new Set<string>(), getterRet = new Map<string, string>()
  for (const line of f.body) {
    const stripped = line.trimStart()
    if (["*", "/*", "#"].some((x) => stripped.startsWith(x))) continue   // docblocks and comments (incl. the next function's)
    const code = line.split("//")[0]
    for (const m of code.matchAll(CALL_RE)) {
      const name = m.groups!.name, recv = m.groups!.recv ?? "", cls = m.groups!.cls
      if (SKIP.has(name) || name.startsWith("assert")) continue
      let target: Func | undefined
      if (cls && !["self", "static", "parent"].includes(cls)) target = byKey.get(tk(cls, name))
      else if (recv === "$this->" || cls === "self" || cls === "static") target = byKey.get(tk(f.cls, name))
      else if (recv.startsWith("$this->") && recv.endsWith("->")) {               // $this->prop->name(
        const prop = recv.slice("$this->".length, -2)
        target = byKey.get(tk(prop.slice(0, 1).toUpperCase() + prop.slice(1), name))
      } else if (recv.startsWith("->") && recv.endsWith("()->")) {                // ->getX()->name(
        const getter = recv.slice(2, -4)
        let ret = getterRet.get(getter)
        if (ret === undefined) { const c = (byName.get(getter) ?? []).filter((g) => g.ret).map((g) => g.ret!); ret = c.length ? c[0] : ""; getterRet.set(getter, ret) }
        if (ret) target = byKey.get(tk(ret, name))
      }
      const distinctive = name.length >= 14 || !COMMON_PREFIX.test(name)
      if (!target && recv === "" && !cls) { const c = (byName.get(name) ?? []).filter((x) => x.cls === null); if (c.length === 1) target = c[0] }
      if (!target && recv.endsWith("->") && !cls && distinctive) { const c = (byName.get(name) ?? []).filter((x) => x.cls); if (c.length === 1) target = c[0] }
      if (target && isTrivial(target)) continue
      if (target && target !== f && !seen.has(target.label)) { seen.add(target.label); out.push(target) }
    }
  }
  return out
}

function tree(seed: Func, byName: ByName, byKey: ByKey, lines: string[], files: Set<string>, methods: Set<string>): void {
  const rec = (f: Func, depth: number, indent: string, path: Set<string>) => {
    if (lines.length >= MAX_LINES) return
    files.add(f.path)
    methods.add(tk(f.cls, f.name.toLowerCase()))
    DISPLAY.set(tk(f.cls, f.name.toLowerCase()), f.label)
    lines.push(`${indent}- \`${f.label}\``)
    if (depth >= DEPTH) return
    const kids = callees(f, byName, byKey).filter((k) => !path.has(k.label))
    for (const k of kids.slice(0, MAX_CHILDREN)) rec(k, depth + 1, indent + "  ", new Set([...path, k.label]))
    if (kids.length > MAX_CHILDREN && lines.length < MAX_LINES) lines.push(`${indent}  - … ${kids.length - MAX_CHILDREN} more`)
  }
  rec(seed, 0, "", new Set([seed.label]))
}

const stripGenerated = (text: string) => text
  .replace(new RegExp(escapeRe(BEGIN_CP) + "[\\s\\S]*?" + escapeRe(END_CP), "g"), "")
  .replace(new RegExp(escapeRe(BEGIN_RS) + "[\\s\\S]*?" + escapeRe(END_RS), "g"), "")

function seedsFor(skill: impact.Doc, byKey: ByKey, byName: ByName): Func[] {
  const seeds: Func[] = [], seen = new Set<string>()
  const text = stripGenerated(read(skill.path))   // never seed from our own output
  const order: [string | null, string][] = [...text.matchAll(impact.CLASS_METHOD_RE)].map((m) => [m[1], m[2]])
  for (const line of splitlines(impact.section(text, "Key files"))) {
    const paths = [...line.matchAll(impact.PATH_RE)].map((m) => m[0]).filter((x) => SRC_EXT.includes(impact.psuffix(x)))
    if (!paths.length) continue
    const cls = impact.pstem(paths[0])
    let cited: [string | null, string][] = []
    for (const b of line.matchAll(impact.BACKTICK_RE)) { const mm = b[1].trim().match(impact.METHOD_TOKEN_RE); if (mm) cited.push([cls, mm[1]]) }
    if (!cited.length) cited = (FILE_FUNCS.get(paths[0]) ?? []).filter((f) => ENTRY_RE.test(f.name)).slice(0, SEEDS_PER_FILE).map((f) => [f.cls, f.name])
    order.push(...cited)
  }
  for (const [cls, name] of order) {
    let f = byKey.get(tk(cls, name))
    if (!f) { const proc = (byName.get(name) ?? []).filter((x) => x.cls === null); f = proc.length === 1 ? proc[0] : undefined }
    if (f && !seen.has(f.label) && !["__construct", "create", "getFormId", "getSubscribedEvents"].includes(f.name)) { seen.add(f.label); seeds.push(f) }
  }
  return seeds
}

function replaceBlock(text: string, heading: string, begin: string, end: string, content: string, before: string | null): string {
  const block = `${heading}\n\n${begin}\n${content}\n${end}\n`
  const pattern = new RegExp(`^${escapeRe(heading)}\\n\\n${escapeRe(begin)}[\\s\\S]*?${escapeRe(end)}\\n`, "m")
  if (pattern.test(text)) return text.replace(pattern, () => block)
  const m = before ? text.match(new RegExp(`^${escapeRe(before)}\\b`, "m")) : null
  if (m) return text.slice(0, m.index) + block + "\n" + text.slice(m.index)
  return text.replace(/\s+$/, "") + "\n\n" + block
}

function setFrontMatter(text: string, key: string, value: string): string {
  const m = text.match(impact.FM_RE)
  if (!m) return text
  let fm = m[1]
  if (new RegExp(`^${key}:`, "m").test(fm)) fm = fm.replace(new RegExp(`^${key}:.*$`, "m"), () => `${key}: ${value}`)
  else fm = fm + `\n${key}: ${value}`
  return `---\n${fm}\n---\n` + text.slice(m[0].length)
}

const pyList = (xs: string[]) => "[" + xs.map((x) => `'${x}'`).join(", ") + "]"

export function main(argv: string[]): number {
  const update = argv.includes("--update"), show = argv.includes("--show") ? argv[argv.indexOf("--show") + 1] : ""
  const [funcs, byName, byKey] = indexCode()
  const skills = impact.loadSkills()   // also computes impact.HUBS
  // Recompute each skill's own references WITHOUT the generated blocks, so a second run is stable.
  for (const s of skills) {
    const raw = stripGenerated(read(s.path))
    const own = new impact.Doc("skill", s.key, s.title, s.path)
    impact.harvestCodeRefs(own, raw, impact.section(raw, "Key files"))
    s.files = own.files; s.classMethods = own.classMethods
  }
  type PS = { doc: impact.Doc; lines: string[]; files: Set<string>; methods: Set<string>; relMethods?: Set<string>; relFiles?: Set<string>; short?: string[] }
  const perSkill = new Map<string, PS>()
  for (const s of skills) {
    const lines: string[] = [], files = new Set<string>(), methods = new Set<string>()
    for (const seed of seedsFor(s, byKey, byName)) {
      if (lines.length >= MAX_LINES) { lines.push(`- … truncated at ${MAX_LINES} lines`); break }
      tree(seed, byName, byKey, lines, files, methods)
    }
    const keyfiles = [...s.files].filter((f) => !f.endsWith("/"))
    perSkill.set(s.key, { doc: s, lines, files: new Set([...files, ...keyfiles]),
      methods: new Set([...methods, ...[...s.classMethods.values()].map(([c, m]) => tk(c, m))]) })
  }
  // Utilities used by many flows (isAdmin(), getCurrentStep() …) do not make two flows related.
  const freq = new Map<string, number>(), ffreq = new Map<string, number>()
  for (const d of perSkill.values()) {
    for (const m of d.methods) freq.set(m, (freq.get(m) ?? 0) + 1)
    for (const f of d.files) ffreq.set(f, (ffreq.get(f) ?? 0) + 1)
  }
  for (const d of perSkill.values()) {
    d.relMethods = new Set([...d.methods].filter((m) => freq.get(m)! <= COMMON))
    d.relFiles = new Set([...d.files].filter((f) => ffreq.get(f)! <= COMMON))
  }
  const related = new Map<string, [string, string[]][]>()
  for (const [aKey, a] of perSkill) {
    const rows: [string, number, string[], string[]][] = []
    for (const [bKey, b] of perSkill) {
      if (aKey === bKey) continue
      const sharedM = [...new Set([...a.relMethods!].filter((m) => b.relMethods!.has(m) && untk(m)[0])
        .map((m) => DISPLAY.get(m) ?? `${untk(m)[0]}::${untk(m)[1]}()`))].sort(cmp)
      const mNames = new Set(sharedM.map((x) => impact.pname(x.split("::")[0])))
      const sharedF = [...a.relFiles!].filter((f) => b.relFiles!.has(f) && !impact.HUBS.has(impact.pstem(f)) && !mNames.has(impact.pname(f)))
        .map((f) => impact.pname(f)).sort(cmp)
      if (sharedM.length || sharedF.length) rows.push([bKey, sharedM.length * 2 + sharedF.length, sharedM, sharedF])
    }
    rows.sort((x, y) => y[1] - x[1] || cmp(x[0], y[0]))
    related.set(aKey, rows.slice(0, MAX_RELATED).map(([k, , m, f]) => [k, [...m, ...f]]))
  }

  // ── Short call path for the LLM: one line per entry point, distinctive callees only ──
  const shortLine = (seed: Func) => {
    const chain = [`\`${seed.label}\``], seen = new Set([seed.label])
    let cur = seed
    for (let h = 0; h < SHORT_HOPS; h++) {
      const nxt = callees(cur, byName, byKey).find((k) => !seen.has(k.label) && !((freq.get(tk(k.cls, k.name.toLowerCase())) ?? 0) > COMMON))
      if (!nxt) break
      seen.add(nxt.label)
      chain.push(nxt.cls === cur.cls ? `\`${nxt.name}()\`` : `\`${nxt.label}\``)
      cur = nxt
    }
    return "- " + chain.join(" → ")
  }
  for (const d of perSkill.values()) {
    const out: string[] = [], seenLines = new Set<string>()
    const seeds = seedsFor(d.doc, byKey, byName)
    const cited = new Set([...d.doc.classMethods.values()].map(([c, m]) => tk(c, m.toLowerCase())))
    const priority = (f: Func) => cited.has(tk(f.cls, f.name.toLowerCase())) ? 0
      : /^(submitForm|on[A-Z]|handle|alter|process|execute|__invoke)/.test(f.name) ? 1
      : ["build", "buildForm", "validateForm", "blockAccess", "access"].includes(f.name) ? 3 : 2
    const ordered = seeds.map((f, i) => [f, i] as const).sort((x, y) => priority(x[0]) - priority(y[0]) || x[1] - y[1]).map(([f]) => f)
    for (const seed of ordered) {
      const line = shortLine(seed)
      if (!seenLines.has(line)) { seenLines.add(line); out.push(line) }
      if (out.length >= SHORT_MAX) break
    }
    d.short = out
  }

  if (show) {
    const d = perSkill.get(show)
    if (!d) { console.error(`unknown skill ${show}`); return 1 }
    console.log("SHORT (in SKILL.md):")
    console.log(d.short!.join("\n") || "(no seed method found)")
    console.log(`\nFULL (in .ai/context/callgraph.json): ${d.lines.length} lines, ${d.files.size} files`)
    console.log("\nrelated_skills:", pyList(related.get(show)!.map(([k]) => k)))
    for (const [k, why] of related.get(show)!) console.log(`  ${k}: ${why.slice(0, 5).join(", ")}`)
    return 0
  }

  let oldGraph: any = {}
  if (isFile(GRAPH)) { try { oldGraph = JSON.parse(read(GRAPH)).skills ?? {} } catch { oldGraph = {} } }
  const graph: any = { generated_by: "bash .ai/scripts/knowledge/scan-callpaths.sh --update", depth: DEPTH, functions_indexed: funcs.length, skills: {} }
  let changed = 0
  const kept: string[] = []
  for (const [key, d] of perSkill) {
    const text = read(d.doc.path)
    let short = d.short!.length ? d.short!.join("\n") : "- (no method of this skill could be resolved in lib/ — cite `Class::method()` in Key files)"
    const current = text.match(new RegExp(escapeRe(BEGIN_CP) + "\\n([\\s\\S]*?)\\n" + escapeRe(END_CP)))
    const currentBody = current ? (current[1].includes("\n\n") ? current[1].slice(current[1].indexOf("\n\n") + 2) : current[1]) : null
    const prevHash = oldGraph[key]?.short_hash
    if (currentBody !== null && prevHash && sha1(currentBody) !== prevHash && currentBody.trim() !== short.trim() && !currentBody.startsWith("Generated from the methods")) {
      short = currentBody   // edited by hand: keep it
      kept.push(key)
    }
    let next = replaceBlock(text, "## Call path", BEGIN_CP, END_CP, SHORT_INTRO + "\n\n" + short, "## Key files")
    next = next.replace(new RegExp("^## Related skills\\n\\n" + escapeRe(BEGIN_RS) + "[\\s\\S]*?" + escapeRe(END_RS) + "\\n\\n?", "gm"), "")
    next = setFrontMatter(next, "related_skills", "[" + related.get(key)!.map(([k]) => k).join(", ") + "]")
    graph.skills[key] = {
      entries: d.short!.map((l) => l.slice(2)),
      tree: d.lines,
      files: [...d.files].filter((f) => SRC_EXT.includes(impact.psuffix(f))).sort(cmp),
      methods: [...d.methods].filter((m) => untk(m)[0]).map((m) => DISPLAY.get(m) ?? `${untk(m)[0]}::${untk(m)[1]}()`).sort(cmp),
      related: related.get(key)!.map(([k, why]) => ({ skill: k, shares: why })),
      short_hash: sha1(short),
    }
    if (next !== text) { changed++; if (update) writeFileSync(d.doc.path, next); else console.log(`STALE ${key}`) }
  }
  const graphText = dumps(graph, 1, false, false) + "\n"
  const graphStale = !isFile(GRAPH) || read(GRAPH) !== graphText
  if (update) {
    writeFileSync(GRAPH, graphText)
    console.log(`Call paths written: ${changed} skill(s) changed, graph callgraph.json (${funcs.length} functions indexed).`)
    if (kept.length) console.log("Hand-edited call paths kept (not regenerated): " + kept.join(", "))
  } else {
    if (graphStale) console.log("STALE callgraph.json")
    console.log(!changed && !graphStale ? "NO CHANGES — call paths, related skills and the call graph are up to date."
      : "Out of date — run: bash .ai/scripts/knowledge/scan-callpaths.sh --update")
  }
  return 0
}
