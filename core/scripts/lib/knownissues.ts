// knownissues.ts — regenerates .ai/known-issues/INDEX.md: one line per known issue (id · status · last seen · modules
// · skills · title), built from the front matter of every .ai/known-issues/*.md. The agent reads it before debugging
// (a few hundred tokens instead of the whole history) and opens only the matching files. Never edit INDEX.md by hand.
//   node .ai/scripts/cli.ts knownissues [--update]        (wrapper: bash .ai/scripts/knowledge/scan-known-issues.sh)
import { existsSync, readdirSync, writeFileSync } from "node:fs"
import { AI } from "./project.ts"
import { read } from "./util.ts"

const KI_DIR = `${AI}/known-issues`, INDEX = `${KI_DIR}/INDEX.md`

/** value of a front-matter key (first block only), like the awk of the original script */
function field(text: string, k: string): string {
  const lines = text.split("\n")
  if (lines[0] !== "---") return ""
  for (const l of lines.slice(1)) {
    if (l === "---") return ""
    if (l.startsWith(k + ":")) return l.slice(k.length + 1).replace(/^[ \t\r\n\v\f]*/, "").replace(/[ \t\r\n\v\f]+#.*$/, "")
  }
  return ""
}

export function render(): string {
  const out = ["# Known issues — index (generated by `.ai/scripts/knowledge/scan-known-issues.sh --update`, do not edit)", "",
    "Search this table by symptom, module or class name BEFORE debugging. Open only the matching files.", "",
    "| ID | Status | Last seen | Modules | Skills | Title | File |", "|---|---|---|---|---|---|---|"]
  const files = existsSync(KI_DIR) ? readdirSync(KI_DIR).filter((f) => f.endsWith(".md") && f !== "INDEX.md" && f !== "README.md").sort() : []
  for (const name of files) {
    const t = read(`${KI_DIR}/${name}`), id = field(t, "id")
    if (!id) continue
    const title = field(t, "title").replace(/^"/, "").replace(/"$/, "")
    const strip = (s: string) => s.replace(/[[\]]/g, "")
    out.push(`| ${id} | ${field(t, "status")} | ${field(t, "last_seen")} | ${strip(field(t, "modules"))} | ${strip(field(t, "skills"))} | ${title.split("|").join("\\|")} | [${name}](${name}) |`)
  }
  return out.join("\n") + "\n"
}

export function main(argv: string[]): number {
  const text = render()
  if (argv.includes("--update")) {
    writeFileSync(INDEX, text)
    console.log(`INDEX.md updated (${text.split("\n").filter((l) => /^\| [A-Z0-9]/.test(l)).length - 1} entries).`)
    return 0
  }
  if (!existsSync(INDEX)) { console.log("INDEX.md missing — run: bash .ai/scripts/knowledge/scan-known-issues.sh --update"); return 1 }
  const cur = read(INDEX)
  if (cur === text) { console.log("NO CHANGES"); return 0 }
  const now = new Set(text.split("\n")), old = new Set(cur.split("\n"))
  console.log("INDEX.md is stale:")
  for (const l of text.split("\n")) if (l && !old.has(l)) console.log(`NEW or CHANGED: ${l}`)
  for (const l of cur.split("\n")) if (l && !now.has(l)) console.log(`REMOVED or OLD: ${l}`)
  console.log("Run: bash .ai/scripts/knowledge/scan-known-issues.sh --update")
  return 0
}
