// claude.ts — the Claude Code target: generates, from the same .ai sources as opencode,
//   CLAUDE.md                 @-imports of core-rules.md, orchestrator.md and claude-code.md (the tool mapping)
//   .claude/settings.json     hooks (UserPromptSubmit → ticket header, SessionStart → state after compact/resume,
//                             PostToolUse → ## Changes + lint) and permissions translated from opencode.json
//   .claude/agents/<x>.md     one subagent per opencode agent (description, tools from its permissions, prompt)
//   .claude/commands/<x>.md   one slash command per opencode command (@-includes .ai/commands/<x>.md; subtask → its subagent)
//   .claude/skills            → link to .ai/skills (same SKILL.md format)
// Our entries carry a marker, so re-running replaces them and keeps anything the human added.
// Used by setup (when project.json "agents" has "claude-code"), doctor (check) and setup --uninstall.
import { cpSync, existsSync, lstatSync, mkdirSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { composed } from "./opencode.ts"
import { AI, ROOT } from "./project.ts"
import { read } from "./util.ts"

const MARK = "<!-- generated by ai-core (node .ai/scripts/cli.ts setup) — edit the source in .ai/, not this file -->"
const HOOK_CMD = (k: string) => `node --experimental-strip-types --no-warnings "$CLAUDE_PROJECT_DIR/.ai/scripts/cli.ts" hook ${k}`
const OLD_CLAUDE_MD = "@.ai/core-rules.md\n@.ai/orchestrator.md\n"
export const CLAUDE_MD = "@.ai/core-rules.md\n@.ai/orchestrator.md\n@.ai/claude-code.md\n"
const say = (s: string) => console.log(s)

function opencodeJson(): any {
  return composed() ?? { agent: {}, command: {}, permission: {} }
}

/** opencode bash glob → Claude Code rules (prefix matches): "git diff*" → Bash(git diff:*). A leading * means
 *  "contains" in opencode ("*drush cim*"): Claude Code has no such rule, so the usual wrappers are added too
 *  (Bash(drush cim:*), Bash(ddev drush cim:*), Bash(wsl.exe … ) — otherwise `ddev drush cim` would pass as Bash(ddev:*). */
function rules(glob: string): string[] {
  const contains = glob.startsWith("*")
  const g = glob.replace(/^\*+/, "").trim()
  const one = (x: string) => (g.endsWith("*") ? `Bash(${x.replace(/\*+$/, "").trim()}:*)` : `Bash(${x})`)
  return contains ? [one(g), one(`ddev ${g}`), one(`ddev exec ${g}`)] : [one(g)]
}

function settings(): any {
  const perm = opencodeJson().permission ?? {}
  const allow = new Set<string>(["Read", "Grep", "Glob", "Bash(node --experimental-strip-types --no-warnings .ai/scripts/cli.ts:*)",
    "Bash(node .ai/scripts/cli.ts:*)", "Bash(bash .ai/scripts/:*)"])
  const deny = new Set<string>(["Read(./.env)", "Read(./.env.*)", "Read(**/*.key)", "Read(**/*.pem)"])
  const ask = new Set<string>()
  for (const [g, v] of Object.entries<string>(perm.bash ?? {})) {
    if (g === "*") continue
    for (const r of rules(g)) ({ allow, deny, ask } as Record<string, Set<string>>)[v]?.add(r)
  }
  return {
    permissions: { allow: [...allow], deny: [...deny], ask: [...ask] },
    hooks: {
      UserPromptSubmit: [{ hooks: [{ type: "command", command: HOOK_CMD("prompt"), timeout: 20 }] }],
      SessionStart: [{ matcher: "compact|resume", hooks: [{ type: "command", command: HOOK_CMD("session"), timeout: 20 }] }],
      PostToolUse: [{ matcher: "Edit|Write|MultiEdit", hooks: [{ type: "command", command: HOOK_CMD("edit"), timeout: 120 }] }],
    },
  }
}

const ours = (h: any) => JSON.stringify(h).includes(".ai/scripts/cli.ts\\\" hook") || JSON.stringify(h).includes(".ai/scripts/cli.ts hook")

function mergeSettings(file: string, add: any | null): void {
  const cur = existsSync(file) ? JSON.parse(read(file)) : {}
  cur.hooks ??= {}
  for (const ev of Object.keys(cur.hooks)) { cur.hooks[ev] = (cur.hooks[ev] as any[]).filter((h) => !ours(h)); if (!cur.hooks[ev].length) delete cur.hooks[ev] }
  if (add) for (const [ev, hs] of Object.entries<any[]>(add.hooks)) cur.hooks[ev] = [...(cur.hooks[ev] ?? []), ...hs]
  if (!Object.keys(cur.hooks).length) delete cur.hooks
  if (add) {
    cur.permissions ??= {}
    for (const k of ["allow", "deny", "ask"]) cur.permissions[k] = [...new Set([...(cur.permissions[k] ?? []), ...add.permissions[k]])]
  }
  mkdirSync(join(ROOT, ".claude"), { recursive: true })
  writeFileSync(file, JSON.stringify(cur, null, 2) + "\n")
}

/** the files we generate: path → content */
export function expected(): Map<string, string> {
  const oc = opencodeJson(), out = new Map<string, string>()
  for (const [name, a] of Object.entries<any>(oc.agent ?? {})) {
    if (name === "build" || name === "plan" || !a.prompt) continue
    const src = (a.prompt.match(/\{file:\.\/(.+)\}/) ?? [])[1]
    if (!src || !existsSync(join(ROOT, src))) continue
    const p = a.permission ?? {}
    const tools = ["Read", "Grep", "Glob"]
    if (p.edit !== "deny") tools.push("Edit", "Write", "MultiEdit")
    if (p.bash && p.bash !== "deny") tools.push("Bash")
    const desc = String(a.description ?? name).replace(/\n/g, " ")
    out.set(`.claude/agents/${name}.md`, `---\nname: ${name}\ndescription: ${JSON.stringify(desc)}\ntools: ${tools.join(", ")}\n---\n${MARK}\n\n` +
      (p.edit === "deny" ? "You are read-only: never edit or write files.\n\n" : "") + read(join(ROOT, src)))
  }
  for (const [name, c] of Object.entries<any>(oc.command ?? {})) {
    const src = (String(c.template ?? "").match(/\{file:\.\/(.+)\}/) ?? [])[1]
    if (!src) continue
    const desc = String(c.description ?? name).replace(/\n/g, " ")
    const delegate = c.subtask && c.agent ? `Run this whole command in the \`${c.agent}\` subagent (Task tool): give it the instructions below and the arguments, then relay its answer and its ▶ Next line.\n\n` : ""
    out.set(`.claude/commands/${name}.md`, `---\ndescription: ${JSON.stringify(desc)}\nargument-hint: ${JSON.stringify("[arguments]")}\n---\n${MARK}\n\n${delegate}Arguments: $ARGUMENTS\n\n@${src}\n`)
  }
  return out
}

export function install(): void {
  // CLAUDE.md: created, or upgraded when it is ai-core's older one; a hand-written one is kept (doctor says what to add)
  const md = join(ROOT, "CLAUDE.md")
  if (!existsSync(md) || read(md) === OLD_CLAUDE_MD) { writeFileSync(md, CLAUDE_MD); say("✔ CLAUDE.md (imports core-rules, orchestrator, claude-code)") }
  mergeSettings(join(ROOT, ".claude", "settings.json"), settings())
  say("✔ .claude/settings.json: hooks UserPromptSubmit · SessionStart · PostToolUse, permissions from opencode.json")
  const want = expected()
  for (const dir of [".claude/agents", ".claude/commands"]) {          // drop our files that no longer exist in .ai
    const d = join(ROOT, dir)
    if (existsSync(d)) for (const f of readdirSync(d)) { const rel = `${dir}/${f}`; if (!want.has(rel) && read(join(d, f)).includes(MARK)) rmSync(join(d, f)) }
  }
  let n = 0
  for (const [rel, content] of want) {
    const f = join(ROOT, rel)
    if (existsSync(f) && !read(f).includes(MARK)) { say(`⚠ ${rel} exists and is not ours — left as is`); continue }
    mkdirSync(join(f, ".."), { recursive: true }); writeFileSync(f, content); n++
  }
  say(`✔ .claude/agents + .claude/commands: ${n} file(s)`)
  const link = join(ROOT, ".claude", "skills"), target = join(AI, "skills")
  let st; try { st = lstatSync(link) } catch { st = null }
  if (!st) {
    try { symlinkSync(process.platform === "win32" ? target : "../.ai/skills", link, process.platform === "win32" ? "junction" : "dir"); say("✔ .claude/skills → .ai/skills") }
    catch { cpSync(target, link, { recursive: true }); say("✔ .claude/skills (copy: no permission for links — re-run setup after the skills change)") }
  }
}

export function uninstall(): void {
  const file = join(ROOT, ".claude", "settings.json")
  if (existsSync(file)) { mergeSettings(file, null); say("✔ .claude/settings.json: our hooks removed (permissions kept)") }
  for (const dir of [".claude/agents", ".claude/commands"]) {
    const d = join(ROOT, dir)
    if (existsSync(d)) for (const f of readdirSync(d)) if (read(join(d, f)).includes(MARK)) rmSync(join(d, f))
  }
  const link = join(ROOT, ".claude", "skills")
  try { if (lstatSync(link).isSymbolicLink()) { rmSync(link); say("✔ .claude/skills link removed") } } catch { /* */ }
}

/** for doctor: [status, detail] */
export function check(): [string, string][] {
  const out: [string, string][] = []
  const md = join(ROOT, "CLAUDE.md")
  out.push(!existsSync(md) ? ["FAIL", "CLAUDE.md missing"]
    : CLAUDE_MD.trim().split("\n").every((l) => read(md).includes(l)) ? ["OK", "CLAUDE.md imports core-rules, orchestrator, claude-code"]
    : ["WARN", `CLAUDE.md does not import all of: ${CLAUDE_MD.trim().split("\n").join(" ")}`])
  const sf = join(ROOT, ".claude", "settings.json")
  const s = existsSync(sf) ? JSON.parse(read(sf)) : {}
  const evs = ["UserPromptSubmit", "SessionStart", "PostToolUse"].filter((e) => !(s.hooks?.[e] ?? []).some(ours))
  out.push(evs.length ? ["FAIL", `.claude/settings.json lacks our hooks: ${evs.join(", ")}`] : ["OK", ".claude/settings.json hooks: ticket header, compact/resume state, edit tracking"])
  const stale = [...expected()].filter(([rel, c]) => !existsSync(join(ROOT, rel)) || (read(join(ROOT, rel)).includes(MARK) && read(join(ROOT, rel)) !== c)).map(([r]) => r)
  out.push(stale.length ? ["WARN", `${stale.length} agent/command file(s) missing or older than .ai: ${stale.slice(0, 3).join(", ")}`] : ["OK", ".claude agents and commands match .ai"])
  const link = join(ROOT, ".claude", "skills")
  let ok = false
  try { ok = lstatSync(link).isSymbolicLink() ? existsSync(join(link, ".")) : existsSync(link) } catch { ok = false }
  out.push(ok ? ["OK", ".claude/skills → .ai/skills"] : ["WARN", ".claude/skills missing: Claude Code will not see the skills"])
  return out
}

