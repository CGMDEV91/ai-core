// callpaths.ts — every skill's call path, from the code index (.ai/context/code-index.json) of any stack.
// For each skill: the methods it cites (Key files + Class::method() / name() in its text) are the seeds; their callees,
// two levels deep, are the flow's call path. Written as a short `## Call path` block in the SKILL.md (one line per
// entry point), the full tree in .ai/context/callgraph.json (what /impact reads), and `related_skills` in the front
// matter (skills sharing a distinctive method or file). The Drupal stack replaces this file with its own PHP resolver.
//   node .ai/scripts/cli.ts callpaths [--update] [--show SKILL]      (wrapper: bash .ai/scripts/knowledge/scan-callpaths.sh)
import { createHash } from "node:crypto"
import { writeFileSync } from "node:fs"
import * as impact from "./impact.ts"
import { AI } from "./project.ts"
import { cmp, dumps, escapeRe, isFile, read } from "./util.ts"

const DEPTH = 2, MAX_CHILDREN = 6, MAX_LINES = 70, SEEDS_PER_FILE = 3, MAX_RELATED = 8, SHORT_HOPS = 3, SHORT_MAX = 10, COMMON = 5
const GRAPH = `${AI}/context/callgraph.json`
const SHORT_INTRO = "Main path of each entry point (distinctive calls only). Full call tree, callers and files: " +
  "`.ai/context/callgraph.json`, or the tools `where` / `callers`."
const BEGIN_CP = "<!-- call-path:begin — generated by `bash .ai/scripts/knowledge/scan-callpaths.sh --update`; hand edits are kept -->"
const END_CP = "<!-- call-path:end -->"
const sha1 = (text: string) => createHash("sha1").update(text.trim(), "utf8").digest("hex").slice(0, 12)

type Fn = { label: string; cls: string; name: string; file: string; callees: string[] }
const key = (c: string, n: string) => `${c}\u0000${n.toLowerCase()}`

/** the code index as functions: "Class::method()" → cls Class; "name()" → cls = the file's name (a component, a module) */
function functions(): [Fn[], Map<string, Fn>, Map<string, Fn[]>] {
  let methods: Record<string, any> = {}
  try { methods = JSON.parse(read(`${AI}/context/code-index.json`)).methods ?? {} } catch { /* no index yet */ }
  const fns: Fn[] = [], byKey = new Map<string, Fn>(), byFile = new Map<string, Fn[]>()
  for (const [label, m] of Object.entries<any>(methods)) {
    const bare = impact.prstrip(label, "()"), i = bare.indexOf("::")
    const f: Fn = { label, cls: i >= 0 ? bare.slice(0, i) : impact.pstem(String(m.file)), name: i >= 0 ? bare.slice(i + 2) : bare, file: String(m.file), callees: m.callees ?? [] }
    fns.push(f); byKey.set(key(f.cls, f.name), f)
    if (!byFile.has(f.file)) byFile.set(f.file, []); byFile.get(f.file)!.push(f)
  }
  return [fns, byKey, byFile]
}

function stripGenerated(text: string): string {
  return text.replace(new RegExp(`${escapeRe(BEGIN_CP)}[\\s\\S]*?${escapeRe(END_CP)}\\n?`, "g"), "")
}

function replaceBlock(text: string, heading: string, content: string, before: string | null): string {
  const block = `${heading}\n\n${BEGIN_CP}\n${content}\n${END_CP}\n`
  const pattern = new RegExp(`^${escapeRe(heading)}\\n\\n${escapeRe(BEGIN_CP)}[\\s\\S]*?${escapeRe(END_CP)}\\n`, "m")
  if (pattern.test(text)) return text.replace(pattern, () => block)
  const m = before ? text.match(new RegExp(`^${escapeRe(before)}\\b`, "m")) : null
  if (m) return text.slice(0, m.index) + block + "\n" + text.slice(m.index)
  return text.replace(/\s+$/, "") + "\n\n" + block
}

function setFrontMatter(text: string, k: string, value: string): string {
  const m = text.match(impact.FM_RE)
  if (!m) return text
  let fm = m[1]
  if (new RegExp(`^${k}:`, "m").test(fm)) fm = fm.replace(new RegExp(`^${k}:.*$`, "m"), () => `${k}: ${value}`)
  else fm = fm + `\n${k}: ${value}`
  return `---\n${fm}\n---\n` + text.slice(m[0].length)
}

export function main(argv: string[]): number {
  const update = argv.includes("--update"), show = argv.includes("--show") ? argv[argv.indexOf("--show") + 1] : ""
  const [fns, byKey, byFile] = functions()
  const resolve = (label: string) => fns.find((f) => f.label === label)
  const skills = impact.loadSkills()
  for (const s of skills) {   // the skill's own references, without the generated blocks: a second run is stable
    const own = new impact.Doc("skill", s.key, s.title, s.path), raw = stripGenerated(read(s.path))
    impact.harvestCodeRefs(own, raw, impact.section(raw, "Key files"))
    s.files = own.files; s.classMethods = own.classMethods
  }
  type PS = { doc: impact.Doc; seeds: Fn[]; lines: string[]; files: Set<string>; methods: Set<string>; short: string[] }
  const per = new Map<string, PS>()
  for (const s of skills) {
    const seeds: Fn[] = []
    for (const [c, m] of s.classMethods.values()) { const f = byKey.get(key(c, m)); if (f && !seeds.includes(f)) seeds.push(f) }
    for (const file of [...s.files].filter((f) => !f.endsWith("/")).sort(cmp))   // a Key file without cited methods: its first functions
      if (!seeds.some((f) => f.file === file)) seeds.push(...(byFile.get(file) ?? []).slice(0, SEEDS_PER_FILE))
    const lines: string[] = [], files = new Set<string>(), methods = new Set<string>()
    const walk = (f: Fn, depth: number, indent: string) => {
      if (lines.length >= MAX_LINES) return
      lines.push(`${indent}- ${f.label}  ${f.file}`); files.add(f.file); methods.add(f.label)
      if (depth >= DEPTH) return
      for (const c of f.callees.slice(0, MAX_CHILDREN)) { const g = resolve(c); if (g && !methods.has(g.label)) walk(g, depth + 1, indent + "  ") }
    }
    for (const seed of seeds) walk(seed, 0, "")
    for (const f of s.files) if (!f.endsWith("/")) files.add(f)
    per.set(s.key, { doc: s, seeds, lines, files, methods, short: [] })
  }
  // utilities used by many flows do not make two flows related, nor belong to a short path
  const freq = new Map<string, number>(), ffreq = new Map<string, number>()
  for (const d of per.values()) { for (const m of d.methods) freq.set(m, (freq.get(m) ?? 0) + 1); for (const f of d.files) ffreq.set(f, (ffreq.get(f) ?? 0) + 1) }
  const related = new Map<string, [string, string[]][]>()
  for (const [a, A] of per) {
    const rows: [string, number, string[]][] = []
    for (const [b, B] of per) {
      if (a === b) continue
      const m = [...A.methods].filter((x) => B.methods.has(x) && freq.get(x)! <= COMMON).sort(cmp)
      const f = [...A.files].filter((x) => B.files.has(x) && ffreq.get(x)! <= COMMON && !impact.HUBS.has(impact.pstem(x))).map(impact.pname).sort(cmp)
      if (m.length || f.length) rows.push([b, m.length * 2 + f.length, [...m, ...f]])
    }
    rows.sort((x, y) => y[1] - x[1] || cmp(x[0], y[0]))
    related.set(a, rows.slice(0, MAX_RELATED).map(([k, , why]) => [k, why]))
  }
  for (const d of per.values()) {
    const seen = new Set<string>()
    for (const seed of d.seeds) {
      const chain = [`\`${seed.label}\``], used = new Set([seed.label])
      let cur = seed
      for (let h = 0; h < SHORT_HOPS; h++) {
        const nxt = cur.callees.map(resolve).find((g) => g && !used.has(g.label) && (freq.get(g.label) ?? 0) <= COMMON)
        if (!nxt) break
        used.add(nxt.label); chain.push(nxt.cls === cur.cls ? `\`${nxt.name}()\`` : `\`${nxt.label}\``); cur = nxt
      }
      const line = "- " + chain.join(" → ")
      if (!seen.has(line)) { seen.add(line); d.short.push(line) }
      if (d.short.length >= SHORT_MAX) break
    }
  }
  if (show) {
    const d = per.get(show)
    if (!d) { console.error(`unknown skill ${show}`); return 1 }
    console.log("SHORT (in SKILL.md):\n" + (d.short.join("\n") || "(no seed method found)"))
    console.log(`\nFULL (in .ai/context/callgraph.json): ${d.lines.length} lines, ${d.files.size} files`)
    console.log("\nrelated_skills: [" + related.get(show)!.map(([k]) => `'${k}'`).join(", ") + "]")
    return 0
  }
  const graph: any = { generated_by: "bash .ai/scripts/knowledge/scan-callpaths.sh --update", depth: DEPTH, functions_indexed: fns.length, skills: {} }
  let changed = 0
  for (const [k, d] of per) {
    const text = read(d.doc.path)
    const short = d.short.length ? d.short.join("\n") : "- (no method of this skill is in the code index — cite `Class::method()` or `name()` with its file in Key files)"
    let next = replaceBlock(text, "## Call path", SHORT_INTRO + "\n\n" + short, "## Key files")
    next = setFrontMatter(next, "related_skills", "[" + related.get(k)!.map(([x]) => x).join(", ") + "]")
    graph.skills[k] = { entries: d.short.map((l) => l.slice(2)), tree: d.lines, files: [...d.files].sort(cmp), methods: [...d.methods].sort(cmp),
      related: related.get(k)!.map(([s, why]) => ({ skill: s, shares: why })), short_hash: sha1(short) }
    if (next !== text) { changed++; if (update) writeFileSync(d.doc.path, next); else console.log(`STALE ${k}`) }
  }
  const graphText = dumps(graph, 1, false, false) + "\n", stale = !isFile(GRAPH) || read(GRAPH) !== graphText
  if (update) { writeFileSync(GRAPH, graphText); console.log(`Call paths written: ${changed} skill(s) changed, graph callgraph.json (${fns.length} functions indexed).`) }
  else console.log(!changed && !stale ? "NO CHANGES — call paths, related skills and the call graph are up to date." : "Out of date — run: bash .ai/scripts/knowledge/scan-callpaths.sh --update")
  return 0
}
