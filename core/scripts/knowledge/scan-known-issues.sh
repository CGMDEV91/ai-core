#!/usr/bin/env bash
# scan-known-issues.sh
# Regenerates .ai/known-issues/INDEX.md — one line per known issue (id · status · modules · title),
# built from the front matter of every .ai/known-issues/*.md file.
#
# The index is what the agent reads before debugging (a few hundred tokens instead of the whole
# history); it then opens only the files whose title or modules match the symptom.
#
# Usage:
#   bash .ai/scripts/knowledge/scan-known-issues.sh           — print the diff between the index and the files
#   bash .ai/scripts/knowledge/scan-known-issues.sh --update  — rewrite INDEX.md
#
# Never edit INDEX.md by hand: it is generated.

set -euo pipefail

AI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"   # .ai/scripts/knowledge → .ai
KI_DIR="$AI_DIR/known-issues"
INDEX="$KI_DIR/INDEX.md"

field() { # field <file> <key> — value of a front-matter key (first block only)
  awk -v k="$2" '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && index($0, k ":") == 1 { sub("^" k ":[[:space:]]*", ""); sub(/[[:space:]]+#.*$/, ""); print; exit }
  ' "$1"
}

render() {
  echo "# Known issues — index (generated by \`.ai/scripts/knowledge/scan-known-issues.sh --update\`, do not edit)"
  echo ""
  echo "Search this table by symptom, module or class name BEFORE debugging. Open only the matching files."
  echo ""
  echo "| ID | Status | Last seen | Modules | Skills | Title | File |"
  echo "|---|---|---|---|---|---|---|"
  find "$KI_DIR" -maxdepth 1 -type f -name '*.md' ! -name 'INDEX.md' ! -name 'README.md' | LC_ALL=C sort |
  while IFS= read -r f; do
    id="$(field "$f" id)"
    [ -n "$id" ] || continue
    title="$(field "$f" title)"; title="${title#\"}"; title="${title%\"}"
    status="$(field "$f" status)"
    last="$(field "$f" last_seen)"
    modules="$(field "$f" modules | tr -d '[]')"
    skills="$(field "$f" skills | tr -d '[]')"
    echo "| $id | $status | $last | $modules | $skills | ${title//|/\\|} | [$(basename "$f")]($(basename "$f")) |"
  done
}

if [[ "${1:-}" == "--update" ]]; then
  render > "$INDEX"
  echo "INDEX.md updated ($(grep -c '^| [A-Z0-9]' "$INDEX" | awk '{print $1 - 1}') entries)."
  exit 0
fi

if [[ ! -f "$INDEX" ]]; then
  echo "INDEX.md missing — run: bash .ai/scripts/knowledge/scan-known-issues.sh --update"
  exit 1
fi

if diff -q <(render) "$INDEX" >/dev/null; then
  echo "NO CHANGES"
else
  echo "INDEX.md is stale:"
  diff <(render) "$INDEX" | grep '^[<>]' | sed 's/^</NEW or CHANGED:/; s/^>/REMOVED or OLD:/'
  echo "Run: bash .ai/scripts/knowledge/scan-known-issues.sh --update"
fi
